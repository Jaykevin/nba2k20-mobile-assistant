RULE_BASE, TUNE_BASE, DUNK_BASE = 200, 300, 1000
DUNK_COUNT = 527
CFG_SIZE = DUNK_BASE + DUNK_COUNT
STAT_RULE_BASE, STAT_DUNK_BASE = 200, 1000


def gen_c():
    out = ['/* Generated by gen/gen.py - do not edit. */', '#pragma once', '']
    out.append('enum {')
    for i, (name, *_rest) in enumerate(SCALARS):
        out.append(f'    CFG_{name} = {i},')
    out.append(f'    CFG_SCALAR_COUNT = {len(SCALARS)},')
    out.append(f'    CFG_RULE_BASE = {RULE_BASE}, RULE_COUNT = {len(RULES)},')
    out.append(f'    CFG_TUNE_BASE = {TUNE_BASE}, TUNE_KEYS = {len(TUNABLES)},')
    out.append(f'    CFG_DUNK_BASE = {DUNK_BASE}, DUNK_ACTION_COUNT = {DUNK_COUNT},')
    out.append(f'    CFG_SIZE = {CFG_SIZE},')
    out.append('};')
    out.append('enum {')
    for i, name in enumerate(STATS):
        out.append(f'    ST_{name} = {i},')
    out.append(f'    ST_COUNT = {len(STATS)},')
    out.append(f'    ST_RULE_BASE = {STAT_RULE_BASE}, ST_DUNK_BASE = {STAT_DUNK_BASE},')
    out.append('};')
    out.append('static const int cfg_default[CFG_SCALAR_COUNT] = {' + ', '.join(str(s[3]) for s in SCALARS) + '};')
    out.append('static const int cfg_min[CFG_SCALAR_COUNT] = {' + ', '.join(str(s[4]) for s in SCALARS) + '};')
    out.append('static const int cfg_max[CFG_SCALAR_COUNT] = {' + ', '.join(str(s[5]) for s in SCALARS) + '};')
    (NATIVE / 'gen_settings.h').write_text('\n'.join(out) + '\n', encoding='utf-8')


def jstr(items):
    return '{' + ', '.join('"' + x.replace('"', '\\"') + '"' for x in items) + '}'


def gen_java():
    lines = ['/* Generated by gen/gen.py - do not edit. */', 'package com.local.nba2k20;', '',
             'final class S {', '    private S() { }', f'    static final String VERSION = "{VERSION}";']
    for i, (name, *_r) in enumerate(SCALARS):
        lines.append(f'    static final int {name} = {i};')
    lines.append(f'    static final int SCALAR_COUNT = {len(SCALARS)};')
    lines.append(f'    static final int RULE_BASE = {RULE_BASE}, TUNE_BASE = {TUNE_BASE}, DUNK_BASE = {DUNK_BASE};')
    lines.append(f'    static final int TUNE_KEYS = {len(TUNABLES)}, DUNK_COUNT = {DUNK_COUNT};')
    lines.append('    static final String[] KEY = ' + jstr([s[1] for s in SCALARS]) + ';')
    lines.append('    static final boolean[] BOOL = {' + ', '.join('true' if s[2] == 'bool' else 'false' for s in SCALARS) + '};')
    lines.append('    static final int[] DEF = {' + ', '.join(str(s[3]) for s in SCALARS) + '};')
    lines.append('    static final int[] MIN = {' + ', '.join(str(s[4]) for s in SCALARS) + '};')
    lines.append('    static final int[] MAX = {' + ', '.join(str(s[5]) for s in SCALARS) + '};')
    lines.append('    static final String[] TUNABLES = ' + jstr(TUNABLES) + ';')
    lines.append('    static final String[] RULES = ' + jstr(RULES) + ';')
    for i, name in enumerate(STATS):
        lines.append(f'    static final int ST_{name} = {i};')
    lines.append(f'    static final int ST_RULE_BASE = {STAT_RULE_BASE}, ST_DUNK_BASE = {STAT_DUNK_BASE};')
    lines.append('}')
    (JAVA / 'S.java').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def gen_dunks():
    data = json.loads(DUNK_JSON.read_text(encoding='utf-8'))
    actions = sorted(data['actions'], key=lambda a: a['index'])
    assert [a['index'] for a in actions] == list(range(DUNK_COUNT))
    packages = {p['id']: p['name'] for p in data['packages']}
    pack_names = [packages[-1]] + [packages[i] for i in range(1, 65)]
    # C: sorted CRC -> index for binary search
    pairs = sorted((a['crc'], a['index']) for a in actions)
    c = ['/* Generated by gen/gen.py - do not edit. */', '#pragma once',
         'static const unsigned dunk_sorted_crc[DUNK_ACTION_COUNT] = {' + ','.join('0x%08xu' % p[0] for p in pairs) + '};',
         'static const unsigned short dunk_sorted_index[DUNK_ACTION_COUNT] = {' + ','.join(str(p[1]) for p in pairs) + '};']
    (NATIVE / 'gen_dunks.h').write_text('\n'.join(c) + '\n', encoding='utf-8')
    j = ['/* Generated by gen/gen.py - do not edit. */', 'package com.local.nba2k20;', '',
         'final class DunkData {', '    private DunkData() { }',
         f'    static final int COUNT = {DUNK_COUNT};',
         '    /** Package names; index 0 = generic pool, 1..64 = game dunk packages. */',
         '    static final String[] PACKAGE_NAMES = ' + jstr(pack_names) + ';',
         '    static final byte[] PACKAGE = {' + ','.join(str(a['package']) for a in actions) + '};',
         '    static final byte[] VARIANT = {' + ','.join(str(a['variant']) for a in actions) + '};',
         '    static final long[] MEMBERS = {' + ','.join(str(a['package_mask'] - (1 << 64) if a['package_mask'] >= (1 << 63) else a['package_mask']) + 'L' for a in actions) + '};',
         '    static final boolean[] GENERIC = {' + ','.join('true' if a['generic'] else 'false' for a in actions) + '};',
         '    static final boolean[] ROTATION = {' + ','.join('true' if a['rotation'] else 'false' for a in actions) + '};',
         '    /** Category ids: -2 all, -3 360 rotation, -1 generic pool, 1..64 packages. */',
         '    static boolean inCategory(int index, int category) {',
         '        if (category == -2) return true;',
         '        if (category == -3) return ROTATION[index];',
         '        if (category == -1) return GENERIC[index];',
         '        return category >= 1 && category <= 64 && (MEMBERS[index] & (1L << (category - 1))) != 0;',
         '    }',
         '    static String title(int index) {',
         '        return PACKAGE_NAMES[PACKAGE[index]] + " · " + VARIANT[index];',
         '    }',
         '}']
    (JAVA / 'DunkData.java').write_text('\n'.join(j) + '\n', encoding='utf-8')


